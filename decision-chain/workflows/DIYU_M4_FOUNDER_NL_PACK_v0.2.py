def R(aid):
    p = os.path.join(EV, "runs", "%s.json" % aid)
    return json.load(io.open(p, encoding="utf-8")) if os.path.exists(p) else None


def body(aid):
    """取该次冻结运行的用户交付正文，只去掉开头的状态行，其余一字不改。"""
    r = R(aid)
    if not r:
        return None
    o = ((r.get("raw_response") or {}).get("data") or {}).get("outputs") or {}
    t = (o.get("user_delivery") or "")
    lines = t.split("\n")
    while lines and not lines[0].strip():
        lines.pop(0)
    if lines and re.match(r"^\s*status\s*[:：]", lines[0]):
        lines.pop(0)
    while lines and not lines[0].strip():
        lines.pop(0)
    return "\n".join(lines).rstrip()


def ac15(cap, side):
    p = os.path.join(EV, "ac15_eval", "AC15_%s_%s.json" % (cap, side))
    d = json.load(io.open(p, encoding="utf-8"))
    t = (d.get("user_delivery") or "")
    lines = t.split("\n")
    while lines and not lines[0].strip():
        lines.pop(0)
    if lines and re.match(r"^\s*status\s*[:：]", lines[0]):
        lines.pop(0)
    while lines and not lines[0].strip():
        lines.pop(0)
    return "\n".join(lines).rstrip(), d


